"""
AgentForge Workflow Runner.

Executes tasks generated by dispatcher.
"""


from core.runtime.runtime_types import (
    ExecutionStatus
)



class WorkflowRunner:
    """
    Executes agent workflows.
    """



    def __init__(
        self,
        dispatcher,
        provider=None,
        memory=None
    ):

        self.dispatcher = dispatcher

        self.provider = provider

        self.memory = memory



    async def run(
        self,
        context
    ):

        """
        Execute workflow tasks.
        """


        results = []


        tasks = (
            self.dispatcher
            .get_pending_tasks()
        )


        for task in tasks:


            try:

                task.status = (
                    ExecutionStatus.PROCESSING
                )


                result = await self.execute_task(

                    task,

                    context

                )

                if self.memory:
                    await self.memory.store(

                        "last_execution",

                        result

                    )

                task.status = (
                    ExecutionStatus.SUCCESS
                )


                task.result = result


                results.append(result)



            except Exception as error:


                task.status = (
                    ExecutionStatus.ERROR
                )


                task.result = str(error)


                results.append(

                    {
                        "error":
                            str(error)
                    }

                )


        return results



    async def execute_task(
        self,
        task,
        context
    ):

        """
        Execute individual task.
        """


        if self.provider:


            response = await self.provider.generate(

                task.description,

                context

            )


            return response



        return {

            "task":
                task.description,

            "status":
                "completed"

        }